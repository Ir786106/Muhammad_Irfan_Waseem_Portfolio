const assert = require('node:assert/strict');
const fs = require('node:fs');
const crypto = require('node:crypto');
const path = require('node:path');
const privacy = fs.readFileSync('privacy.html','utf8');
const missing = fs.readFileSync('404.html','utf8');
const home = fs.readFileSync('index.html','utf8');
const sitemap = fs.readFileSync('sitemap.xml','utf8');
const server = fs.readFileSync('serve.js','utf8');
const packager = fs.readFileSync('tools/package-site.cjs','utf8');
assert.match(privacy, /<title>Privacy &amp; Data Use/);
assert.match(privacy, /https:\/\/formspree\.io\/legal\/privacy-policy/);
assert.match(privacy, /review feature uses Google sign-in/);
assert.match(privacy, /portfolio-theme/);
assert.match(privacy, /id="case-theme"/);
assert.match(home, /href="privacy\.html"/);
assert.match(sitemap, /privacy\.html/);
assert.ok(packager.includes("'privacy.html'"));
assert.ok(server.includes('isPublicRoute(reqUrl)') && server.includes('PUBLIC_ROOT_FILES') && server.includes('PUBLIC_FOLDERS'));
assert.ok(!missing.includes('irfan-portfolio-ae62a.web.app/style.css'),'404 must not depend on external CSS');
assert.match(missing, /<h1>This page has/);
const styles=missing.match(/<style>([\s\S]+?)<\/style>/)[1];
const hash=crypto.createHash('sha256').update(styles).digest('base64');
assert.ok(missing.includes("'sha256-"+hash+"'"),'404 CSP hash must match inline stylesheet');
const firebase=JSON.parse(fs.readFileSync('firebase.json','utf8'));
const hostingCsp=firebase.hosting.headers.flatMap(x=>x.headers).find(x=>x.key==='Content-Security-Policy').value;
assert.ok(hostingCsp.includes("'sha256-"+hash+"'"),'Firebase 404 policy must permit error stylesheet');
for(const file of ['privacy.html','case-studies.css','case-studies.js','404.html'])assert.ok(fs.existsSync(path.resolve(file)));
console.log('Privacy, error page, CSP hash, public-only preview and packaging checks passed.');
